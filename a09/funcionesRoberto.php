<?php

function sumar($num1, $num2) {
    return $num1 + $num2;
}

function restar($num1, $num2) {
    return $num1 - $num2;
}

function multiplicar($num1, $num2) {
    return $num1 * $num2;
}

function dividir($num1, $num2) {
    return $num1 / $num2;
}

function modulo($num1, $num2) {
    return $num1 % $num2;
}

function iguales($num1, $num2) {
    return $num1 == $num2;
}

function esPar($numero) {
    return $numero % 2 == 0;
}
